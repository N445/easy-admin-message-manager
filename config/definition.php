<?php

declare(strict_types=1);

use Symfony\Component\Config\Definition\Configurator\DefinitionConfigurator;

return static function (DefinitionConfigurator $definition): void {
    $definition->rootNode()
        ->children()
            ->integerNode('max_scan')
                ->info('Non-Doctrine transports only (Redis, AMQP...): maximum number of messages read to filter and paginate them in PHP')
                ->defaultValue(10000)
                ->min(1)
            ->end()
            ->integerNode('breakdown_sample')
                ->info('Most recent failed messages decoded to group failures by class, exception and origin')
                ->defaultValue(1000)
                ->min(1)
            ->end()
            ->arrayNode('batch')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('transport')
                        ->info('Transport receiving batch requeue/remove jobs, null handles them synchronously')
                        ->defaultNull()
                    ->end()
                    ->integerNode('chunk_size')->defaultValue(200)->min(1)->end()
                ->end()
            ->end()
            ->arrayNode('permissions')
                ->addDefaultsIfNotSet()
                ->children()
                    ->scalarNode('view')->defaultValue('ROLE_ADMIN')->end()
                    ->scalarNode('retry')->defaultValue('ROLE_ADMIN')->end()
                    ->scalarNode('remove')->defaultValue('ROLE_ADMIN')->end()
                ->end()
            ->end()
            ->arrayNode('redaction')
                ->addDefaultsIfNotSet()
                ->children()
                    ->arrayNode('keys')
                        ->scalarPrototype()->end()
                        ->defaultValue(['password', 'token', 'secret', 'apiKey', 'authorization'])
                    ->end()
                ->end()
            ->end()
            ->arrayNode('history')
                ->addDefaultsIfNotSet()
                ->children()
                    ->booleanNode('enabled')->defaultFalse()->end()
                    ->scalarNode('connection')->defaultValue('default')->end()
                    ->integerNode('retention_days')->defaultValue(30)->min(1)->end()
                    ->booleanNode('capture_payload')->defaultTrue()->end()
                    ->arrayNode('exclude')
                        ->info('Message classes (or parent classes/interfaces) never recorded')
                        ->scalarPrototype()
                            ->validate()
                                ->ifTrue(static fn (mixed $class): bool => !class_exists((string) $class) && !interface_exists((string) $class))
                                ->thenInvalid('%s is neither a class nor an interface.')
                            ->end()
                        ->end()
                    ->end()
                ->end()
            ->end()
        ->end();
};
